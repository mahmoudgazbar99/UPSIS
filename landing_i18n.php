const LANDING_LANGUAGES = [
    'fr' => ['label' => 'FR', 'name' => 'Français', 'dir' => 'ltr'],
    'ar' => ['label' => 'ع', 'name' => 'العربية', 'dir' => 'rtl'],
    'en' => ['label' => 'EN', 'name' => 'English', 'dir' => 'ltr'],
];

function landing_language(): string
{
    $requested = (string) ($_GET['lang'] ?? '');
    if (isset(LANDING_LANGUAGES[$requested])) {
        setcookie('landing_lang', $requested, [
            'expires' => time() + 31536000,
            'path' => '/',
            'samesite' => 'Lax',
        ]);
        return $requested;
    }
    $saved = (string) ($_COOKIE['landing_lang'] ?? '');
    return isset(LANDING_LANGUAGES[$saved]) ? $saved : 'fr';
}

function landing_country(string $country, string $lang): string
{
    $known = [
        'tunisie' => ['fr' => 'Tunisie', 'ar' => 'تونس', 'en' => 'Tunisia'],
    ];
    $key = mb_strtolower(trim($country));
    return $known[$key][$lang] ?? $country;
}

