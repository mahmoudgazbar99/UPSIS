<?php
declare(strict_types=1);
require dirname(__DIR__) . '/application/pgsql.php';

$checks = [
    ['INSERT IGNORE INTO stage_categorie (nom) VALUES (?)', 'ON CONFLICT DO NOTHING'],
    ['INSERT INTO system_settings (setting_key, setting_value) VALUES (?, ?) ON DUPLICATE KEY UPDATE setting_value = VALUES(setting_value)', 'ON CONFLICT (setting_key) DO UPDATE SET setting_value = EXCLUDED.setting_value'],
    ['SELECT GROUP_CONCAT(DISTINCT e.semaine ORDER BY e.semaine) AS week_list', 'string_agg(DISTINCT e.semaine::text'],
    ['WHERE statut <> "annule" AND date_fin >= CURDATE()', "statut <> 'annule' AND date_fin >= CURRENT_DATE"],
    ['ORDER BY FIELD(g.semestre, "S1", "S2")', "CASE g.semestre WHEN 'S1' THEN 1 WHEN 'S2' THEN 2 ELSE 0 END"],
    ['SELECT id_program <=> ?', 'id_program IS NOT DISTINCT FROM ?'],
    ['SELECT 1 FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM program)', 'SELECT 1 WHERE NOT EXISTS'],
    ['ALTER TABLE presence_etudiant ADD KEY idx_presence_matiere (id_mat)', 'CREATE INDEX idx_presence_matiere ON presence_etudiant (id_mat)'],
    ['INSERT INTO etudiant (id_etudiant) VALUES (?)', 'INSERT INTO etudiant'],
    ['id_setting INT UNSIGNED NOT NULL AUTO_INCREMENT', 'id_setting INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY'],
    ['semaine TINYINT UNSIGNED NOT NULL DEFAULT 1', 'semaine SMALLINT NOT NULL DEFAULT 1'],
    ["UPDATE academic_period SET label_ar = CASE sequence WHEN 1 THEN 'الأول' ELSE CONCAT('', sequence) END", "ELSE CONCAT('', sequence)"],
    ['SELECT 1 WHERE label = \'a"b"c\'', 'a"b"c'],
];
$failed = 0;
foreach ($checks as [$sql, $expect]) {
    $out = pgsql_sql($sql);
    $ok = str_contains($out, $expect);
    echo ($ok ? 'ok  ' : 'FAIL ') . $expect . PHP_EOL;
    if (!$ok) {
        echo $out . PHP_EOL;
        $failed++;
    }
}
exit($failed === 0 ? 0 : 1);
