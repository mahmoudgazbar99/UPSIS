<?php
declare(strict_types=1);

function pg_blob(mixed $value): string
{
    if (is_resource($value)) {
        $value = stream_get_contents($value);
    }
    if (!is_string($value) || $value === '') {
        return '';
    }
    if (str_starts_with($value, '\\x') && preg_match('/^\\\\x[0-9a-fA-F]*$/', $value) === 1) {
        $binary = hex2bin(substr($value, 2));
        return $binary === false ? '' : $binary;
    }
    return $value;
}

/**
 * Turns MySQL double-quoted string literals into PostgreSQL single-quoted
 * strings. Text already inside a single-quoted literal is left unchanged,
 * so a value that contains quotation marks cannot leave that literal.
 */
function pgsql_rewrite_double_quoted_strings(string $sql): string
{
    $length = strlen($sql);
    $out = '';
    $index = 0;
    while ($index < $length) {
        $character = $sql[$index];
        if ($character === "'") {
            $out .= "'";
            $index++;
            while ($index < $length) {
                if ($sql[$index] === "'" && ($index + 1) < $length && $sql[$index + 1] === "'") {
                    $out .= "''";
                    $index += 2;
                    continue;
                }
                $out .= $sql[$index];
                if ($sql[$index] === "'") {
                    $index++;
                    break;
                }
                $index++;
            }
            continue;
        }
        if ($character === '"') {
            $end = strpos($sql, '"', $index + 1);
            $inner = $end === false ? null : substr($sql, $index + 1, $end - $index - 1);
            if ($inner === null || str_contains($inner, '\\')) {
                $out .= $character;
                $index++;
                continue;
            }
            $out .= "'" . str_replace("'", "''", $inner) . "'";
            $index = $end + 1;
            continue;
        }
        $out .= $character;
        $index++;
    }
    return $out;
}

function pgsql_sql(string $sql): string
{
    $trim = ltrim($sql);
    if (preg_match('/^SHOW\s+COLUMNS\s+FROM\s+`?([A-Za-z0-9_]+)`?\s+LIKE\s+([\'"])(.+?)\2/is', $trim, $match)) {
        $table = $match[1];
        $column = str_replace("'", "''", $match[3]);
        return 'SELECT column_name AS "Field", CASE'
            . " WHEN data_type = 'character varying' THEN 'varchar(' || character_maximum_length::text || ')'"
            . " WHEN data_type = 'character' THEN 'char(' || character_maximum_length::text || ')'"
            . " WHEN data_type = 'numeric' THEN 'decimal(' || numeric_precision::text || ',' || numeric_scale::text || ')'"
            . " WHEN data_type = 'timestamp without time zone' THEN 'timestamp'"
            . " WHEN data_type = 'timestamp with time zone' THEN 'timestamp'"
            . " ELSE data_type END AS \"Type\""
            . " FROM information_schema.columns"
            . " WHERE table_schema = current_schema() AND table_name = '" . $table . "' AND column_name = '" . $column . "'";
    }
    if (preg_match('/^SHOW\s+TABLES\s+LIKE\s+([\'"])(.+?)\1/is', $trim, $match)) {
        $table = str_replace("'", "''", $match[2]);
        return "SELECT table_name FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = '" . $table . "'";
    }

    $ignore = (bool) preg_match('/\bINSERT\s+IGNORE\s+INTO\b/i', $sql);
    $sql = preg_replace('/\bINSERT\s+IGNORE\s+INTO\b/i', 'INSERT INTO', $sql) ?? $sql;
    $sql = preg_replace('/\bENUM\s*\((?:[^()]|\'[^\']*\')*\)/i', 'VARCHAR(64)', $sql) ?? $sql;
    $sql = preg_replace('/\b(?:LONG|MEDIUM|TINY)?BLOB\b/i', 'BYTEA', $sql) ?? $sql;
    $sql = preg_replace('/\b(?:LONG|MEDIUM|TINY)TEXT\b/i', 'TEXT', $sql) ?? $sql;
    $sql = preg_replace('/\bDATETIME\b/i', 'TIMESTAMP', $sql) ?? $sql;
    $sql = preg_replace('/\bTINYINT(?!\w)(?:\s*\(\s*\d+\s*\))?(?:\s+UNSIGNED)?/i', 'SMALLINT', $sql) ?? $sql;
    $sql = preg_replace('/\bSMALLINT(?!\w)(?:\s*\(\s*\d+\s*\))?(?:\s+UNSIGNED)?/i', 'SMALLINT', $sql) ?? $sql;
    $sql = preg_replace('/\bBIGINT(?!\w)(?:\s*\(\s*\d+\s*\))?(?:\s+UNSIGNED)?/i', 'BIGINT', $sql) ?? $sql;
    $sql = preg_replace('/\bINT(?:EGER)?(?!\w)(?:\s*\(\s*\d+\s*\))?(?:\s+UNSIGNED)?/i', 'INTEGER', $sql) ?? $sql;
    $sql = preg_replace('/\bAUTO_INCREMENT\b/i', 'GENERATED BY DEFAULT AS IDENTITY', $sql) ?? $sql;
    $sql = preg_replace('/\s+ON\s+UPDATE\s+CURRENT_TIMESTAMP/i', '', $sql) ?? $sql;
    $sql = preg_replace('/\s+ENGINE\s*=\s*InnoDB\b[^\'";]*/i', '', $sql) ?? $sql;
    $sql = preg_replace('/\s+COLLATE\s+[A-Za-z0-9_]+/i', '', $sql) ?? $sql;
    $sql = preg_replace('/\s+CHARACTER\s+SET\s+[A-Za-z0-9_]+/i', '', $sql) ?? $sql;
    $sql = preg_replace('/\bUNIQUE\s+KEY\s+[A-Za-z0-9_]+\s*\(/i', 'UNIQUE (', $sql) ?? $sql;
    $sql = preg_replace('/,\s*KEY\s+[A-Za-z0-9_]+\s*\([^)]+\)/i', '', $sql) ?? $sql;
    $sql = preg_replace(
        '/ALTER\s+TABLE\s+`?([A-Za-z0-9_]+)`?\s+ADD\s+KEY\s+`?([A-Za-z0-9_]+)`?\s*\(([^)]+)\)/i',
        'CREATE INDEX $2 ON $1 ($3)',
        $sql
    ) ?? $sql;
    $sql = preg_replace('/\bADD\s+UNIQUE\s+KEY\s+`?([A-Za-z0-9_]+)`?\s*\(([^)]+)\)/i', 'ADD CONSTRAINT $1 UNIQUE ($2)', $sql) ?? $sql;
    $sql = preg_replace('/`([A-Za-z0-9_]+)`/', '$1', $sql) ?? $sql;
    $sql = preg_replace('/\bJSON_UNQUOTE\s*\(\s*JSON_EXTRACT\s*\(\s*([A-Za-z0-9_\.]+)\s*,\s*([\'"])\$\.([A-Za-z0-9_]+)\2\s*\)\s*\)/i', "(CASE WHEN $1 IS NULL OR btrim($1::text) = '' THEN NULL ELSE $1::jsonb END->>'$3')", $sql) ?? $sql;
    $sql = pgsql_rewrite_double_quoted_strings($sql);
    $sql = str_replace('DATABASE()', 'current_schema()', $sql);
    $sql = preg_replace('/\bCURDATE\s*\(\s*\)/i', 'CURRENT_DATE', $sql) ?? $sql;
    $sql = preg_replace('/\bUNIX_TIMESTAMP\s*\(\s*([^)]+)\)/i', 'EXTRACT(EPOCH FROM $1)::bigint', $sql) ?? $sql;
    $sql = preg_replace('/\s+FROM\s+DUAL\b/i', '', $sql) ?? $sql;
    $sql = preg_replace('/\s*<=>\s*/', ' IS NOT DISTINCT FROM ', $sql) ?? $sql;
    $sql = preg_replace('/TIMESTAMPDIFF\s*\(\s*MINUTE\s*,\s*([^,]+?)\s*,\s*([^)]+?)\)/i', '(EXTRACT(EPOCH FROM ($2 - $1)) / 60)', $sql) ?? $sql;
    $sql = preg_replace('/\bCAST\s*\((.+?)\s+AS\s+UNSIGNED\s*\)/i', 'CAST($1 AS INTEGER)', $sql) ?? $sql;
    $sql = preg_replace('/SUBSTRING_INDEX\s*\(\s*SUBSTRING\s*\(\s*([A-Za-z0-9_\.]+)\s*,\s*(\d+)\s*\)\s*,\s*\'([^\']+)\'\s*,\s*1\s*\)/i', "split_part(substring($1 from $2), '$3', 1)", $sql) ?? $sql;
    $sql = preg_replace('/(?<!I)\bLIKE\b/i', 'ILIKE', $sql) ?? $sql;
    $sql = preg_replace_callback(
        '/\bFIELD\s*\(\s*([A-Za-z0-9_\.]+)\s*,([^()]*)\)/i',
        static function (array $match): string {
            $options = preg_split('/\s*,\s*/', trim($match[2])) ?: [];
            $whens = [];
            foreach (array_values($options) as $index => $option) {
                if ($option === '') {
                    continue;
                }
                $whens[] = 'WHEN ' . $option . ' THEN ' . ($index + 1);
            }
            return 'CASE ' . $match[1] . ' ' . implode(' ', $whens) . ' ELSE 0 END';
        },
        $sql
    ) ?? $sql;
    $sql = preg_replace_callback(
        '/GROUP_CONCAT\s*\(\s*(DISTINCT\s+)?(.+?)\s+ORDER\s+BY\s+(.+?)(?:\s+SEPARATOR\s+\'([^\']*)\')?\s*\)/is',
        static function (array $match): string {
            $hasDistinct = trim($match[1]) !== '';
            $separator = str_replace("'", "''", $match[4] ?? ',');
            $expression = trim($match[2]);
            // PostgreSQL rejects ORDER BY with DISTINCT unless the order key is the aggregated value.
            if ($hasDistinct) {
                return 'string_agg(DISTINCT ' . $expression . "::text, '" . $separator . "')";
            }
            return 'string_agg(' . $expression . "::text, '" . $separator . "' ORDER BY " . trim($match[3]) . ')';
        },
        $sql
    ) ?? $sql;
    $sql = preg_replace('/\bIF\s*\((.+?),\s*(.+?),\s*(.+?)\)/i', 'CASE WHEN $1 THEN $2 ELSE $3 END', $sql) ?? $sql;
    $sql = preg_replace('/\bDROP\s+CHECK\s+/i', 'DROP CONSTRAINT ', $sql) ?? $sql;
    $sql = preg_replace('/\s+AFTER\s+[A-Za-z0-9_]+/i', '', $sql) ?? $sql;
    if (preg_match('/^\s*ALTER\s+TABLE\s+([A-Za-z0-9_]+)\s+MODIFY\s+([A-Za-z0-9_]+)\s+(.+)$/is', trim($sql), $modify)) {
        $rest = trim($modify[3]);
        if (preg_match('/^([A-Za-z]+(?:\s*\(\s*\d+\s*(?:,\s*\d+\s*)?\))?)/', $rest, $typeMatch)) {
            $parts = ['ALTER COLUMN ' . $modify[2] . ' TYPE ' . $typeMatch[1]];
            $suffix = substr($rest, strlen($typeMatch[0]));
            if (preg_match('/\bDEFAULT\s+(.+)$/i', $suffix, $default)) {
                $parts[] = 'ALTER COLUMN ' . $modify[2] . ' SET DEFAULT ' . trim($default[1]);
                $suffix = preg_replace('/\bDEFAULT\s+.+$/i', '', $suffix) ?? $suffix;
            }
            if (preg_match('/\bNOT\s+NULL\b/i', $suffix)) {
                $parts[] = 'ALTER COLUMN ' . $modify[2] . ' SET NOT NULL';
            } elseif (preg_match('/\bNULL\b/i', $suffix)) {
                $parts[] = 'ALTER COLUMN ' . $modify[2] . ' DROP NOT NULL';
            }
            $sql = 'ALTER TABLE ' . $modify[1] . ' ' . implode(', ', $parts);
        }
    }
    if (preg_match('/ON\s+DUPLICATE\s+KEY\s+UPDATE\s+(.+?)\s*$/is', $sql, $update) && preg_match('/INSERT\s+INTO\s+([A-Za-z0-9_]+)/i', $sql, $table)) {
        $targets = [
            'system_settings' => '(setting_key)',
            'stage_eval_ligne' => '(id_dossier, id_critere)',
            'stage_capacite' => '(id_campagne, id_service)',
            'presence_etudiant' => '(id_groupe, id_mat, id_etudiant, date_seance)',
            'institution_logo' => '(asset_key)',
            'schema_migration' => '(version)',
            'stage_doc_type' => '(code)',
            'stage_critere' => '(code)',
            'stage_categorie' => '(nom)',
            'emploi_groupe_pdf' => '(id_groupe)',
        ];
        $name = strtolower($table[1]);
        if (!isset($targets[$name])) {
            throw new RuntimeException('Conflit PostgreSQL non défini pour ' . $name . '.');
        }
        $set = preg_replace('/\b([A-Za-z0-9_]+)\s*=\s*VALUES\(\s*\1\s*\)/i', '$1 = EXCLUDED.$1', $update[1]) ?? $update[1];
        $sql = preg_replace('/ON\s+DUPLICATE\s+KEY\s+UPDATE\s+.+$/is', 'ON CONFLICT ' . $targets[$name] . ' DO UPDATE SET ' . trim($set), $sql) ?? $sql;
    }
    if ($ignore && !preg_match('/ON\s+CONFLICT/i', $sql)) {
        $sql = rtrim($sql, " \t\n\r;");
        $sql .= ' ON CONFLICT DO NOTHING';
    }
    return $sql;
}

final class AppPdo extends PDO
{
    public function prepare(string $query, array $options = []): PDOStatement|false
    {
        return parent::prepare(pgsql_sql($query), $options);
    }

    public function query(string $query, ?int $fetchMode = null, mixed ...$fetchModeArgs): PDOStatement|false
    {
        $sql = pgsql_sql($query);
        if ($fetchMode === null) {
            return parent::query($sql);
        }
        return parent::query($sql, $fetchMode, ...$fetchModeArgs);
    }

    public function exec(string $statement): int|false
    {
        return parent::exec(pgsql_sql($statement));
    }
}
